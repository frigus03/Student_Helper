package com.example.studenthelper;

import android.content.Context;
import android.content.Intent;
import android.provider.CalendarContract;
import android.widget.Toast;

public final class CalendarHelper {

    private CalendarHelper() {
    }

    /**
     * Opens the Google Calendar app pre-filled with the study session event.
     */
    public static void addStudyTaskToCalendar(Context context, StudyTask task) {
        if (context == null || task == null) return;

        try {
            long startTimeMillis = task.getDueDate() > 0 
                    ? task.getDueDate() 
                    : System.currentTimeMillis() + (2 * 60 * 60 * 1000);
                    
            // Default study session duration: 60 minutes
            long endTimeMillis = startTimeMillis + (60 * 60 * 1000);

            Intent intent = new Intent(Intent.ACTION_INSERT)
                    .setData(CalendarContract.Events.CONTENT_URI)
                    .putExtra(CalendarContract.EXTRA_EVENT_BEGIN_TIME, startTimeMillis)
                    .putExtra(CalendarContract.EXTRA_EVENT_END_TIME, endTimeMillis)
                    .putExtra(CalendarContract.Events.TITLE, "Study Session: " + task.getTitle())
                    .putExtra(CalendarContract.Events.DESCRIPTION, "Subject: " + task.getSubject() + "\nGenerated by Student Helper AI")
                    .putExtra(CalendarContract.Events.AVAILABILITY, CalendarContract.Events.AVAILABILITY_BUSY);

            context.startActivity(intent);
        } catch (Exception e) {
            Toast.makeText(context, "Could not open Calendar: " + e.getMessage(), Toast.LENGTH_SHORT).show();
        }
    }
}
